/**
 * 插件预编译：plugin/plugin.ts / schema.ts → 同目录 plugin.js / schema.js。
 *
 * 发布包以预编译入口为准：宿主运行时优先加载 plugin.js，不再逐文件转译 TS；
 * plugin.ts 保留为开发期源码。宿主 #lib/* 与 node_modules 保持 external，插件与宿主
 * 必须共享同一份注册表、数据库与门面实例。
 *
 * 用法：node scripts/compile.mjs
 */
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'plugin');

const HOST_EXTERNAL = ['#lib', '#lib/*', '$lib', '$lib/*', '#app', '#app/*', 'virtual:*'];

async function compile(entry, outfile, label) {
	await build({
		entryPoints: [entry],
		outfile,
		bundle: true,
		format: 'esm',
		platform: 'node',
		target: 'node24',
		packages: 'external',
		external: HOST_EXTERNAL,
		sourcemap: false,
		legalComments: 'none',
		logLevel: 'silent',
		banner: { js: `// ${label} — generated by scripts/compile.mjs; edit the .ts source.` }
	});
}

if (!existsSync(path.join(SRC, 'plugin.ts'))) {
	console.error('[compile] plugin/plugin.ts 不存在');
	process.exit(1);
}

await compile(path.join(SRC, 'plugin.ts'), path.join(SRC, 'plugin.js'), 'plugin/plugin.ts');
console.log('[compile] plugin/plugin.js');
if (existsSync(path.join(SRC, 'schema.ts'))) {
	await compile(path.join(SRC, 'schema.ts'), path.join(SRC, 'schema.js'), 'plugin/schema.ts');
	console.log('[compile] plugin/schema.js');
}
